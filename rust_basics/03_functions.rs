// 第 3 课：函数。
// 运行命令：cargo run --example 03_functions
// 前置知识：先学习第 1 课的类型与作用域，以及第 2 课的 if 表达式。
//
// 预期输出（不含 Cargo 自己的编译和运行提示）：
// 矩形面积：12
// 加一后的值：6
// 块表达式结果：7
// 负数处理结果：0
// 正数处理结果：8
// 收到参数：6
//
// 本课只使用简单数值，把注意力放在输入、返回值和执行顺序上。
// 所有权、借用和复杂数据的传递将在后续课程中单独学习。

// fn 用来定义函数。函数名和参数名通常采用 snake_case（用下划线分隔单词）。
// width、height 是“形参”；调用时传入的 4、3 是“实参”。
// 参数需要写明类型；这样函数的使用者可以清楚知道允许传入什么数据。
// u32 是 32 位无符号整数，适合这里不需要负数的简单示例。
// -> u32 声明返回类型，调用者可以继续使用返回的面积。
fn rectangle_area(width: u32, height: u32) -> u32 {
    // 最后一个没有分号的表达式会成为函数返回值，Rust 不要求在这里写 return。
    // 本例只传入小数值；u32 仍有上限，不能表示任意大的面积。
    width * height
}

fn add_one(value: i32) -> i32 {
    // “表达式”会产生一个值。value + 1 的结果是 i32。
    // 在函数末尾省略分号，可以直接把这个值交给调用者。
    value + 1
}

fn nonnegative_or_zero(value: i32) -> i32 {
    if value < 0 {
        // return 会立即结束当前这一次函数调用，后面的函数体不会再执行。
        // 它适合处理需要提前结束的分支。这里的 0 按返回类型推断为 i32。
        return 0;
    }

    // 输入不是负数时才会到达这里；正常路径用末尾表达式返回即可。
    value
}

// 没写 -> 返回类型的函数，默认返回单元类型 ()，它只有一个值：()。
// “只做一件事、不产生业务结果”的函数常这样写，比如这里输出一条消息。
// () 是一个真实的类型，不是空指针；函数结束时依然会返回一个 () 值。
fn report_number(number: i32) {
    println!("收到参数：{number}");
}

// main 是此示例的程序入口。上面的函数不会仅因“定义在前面”就自动执行。
// 只有执行到函数调用时才进入对应函数体，返回后再继续执行调用位置后面的代码。
// 自定义函数也可以定义在 main 后面；本例放在前面，便于先读清每个函数的职责。
fn main() {
    // 圆括号里是按顺序传入的实参。这里的整数字面量根据参数类型推断为 u32。
    let area = rectangle_area(4, 3);
    println!("矩形面积：{area}");

    // 调用本身也是表达式，返回的 i32 可以保存到变量中。
    let next = add_one(5);
    println!("加一后的值：{next}");

    // 花括号也能构成表达式；这能让一段有局部变量的计算产生最终结果。
    let adjusted = {
        let base = 3; // let 是声明语句，在此用于引入局部变量。
        base * 2 + 1 // 不加分号：块表达式的值为 7，类型推断为 i32。
    }; // 这里的分号结束外层 let 语句，并不属于块内最后一个表达式。
    // base 的作用域已结束，外面只保留块返回的结果 adjusted。
    println!("块表达式结果：{adjusted}");

    println!("负数处理结果：{}", nonnegative_or_zero(-2));
    println!("正数处理结果：{}", nonnegative_or_zero(8));

    // report_number 在调用时先输出一行，然后返回 ()；用显式类型观察它的返回类型。
    // 下划线开头的变量名表示我们有意暂时不使用此结果，避免未使用变量的警告。
    let _result: () = report_number(6);

    // 常见错误 1：实参类型不匹配。
    // 观察方法：只取消下一行的 //，再执行本课的运行命令。
    // add_one(1.5);
    // 1.5 是浮点数，而形参要求 i32，编译器会拒绝自动把它当作整数。
    // 修复：改成整数 add_one(1)，或有明确需求时重新设计函数的参数与返回类型。

    // 常见错误 2：参数数量不匹配。
    // 观察方法：只取消下一行的 //，再执行本课的运行命令。
    // rectangle_area(4);
    // 两个参数都必须提供；修复：补上高度，例如 rectangle_area(4, 3)。

    // 常见错误 3：把块的末尾表达式加上分号，块的值就变成 ()。
    // 观察方法：只取消下面这一行的 //，保持其他反例仍被注释。
    // let wrong: i32 = { 2 + 3; };
    // 2 + 3; 会计算后丢弃结果，块中也没有其他返回值，因此得到 () 而非 i32。
    // 修复：删除块内的分号，写成 let correct: i32 = { 2 + 3 };。
}

